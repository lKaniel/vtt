#!/usr/bin/env python3
"""Monster token art: write the prompt pack, and import generated pictures.

    python3 scripts/token-art.py prompts
        Rewrites docs/token-art/prompts.md from docs/token-art/creatures.json.

    python3 scripts/token-art.py import <folder> [<folder> ...]
        Takes every picture named after a monster id (goblin.png, adult-red-dragon.jpg,
        a 2024 alias such as goblin-warrior.png works too), keys out the flat green or
        magenta background, trims it, centres it on a transparent square and saves it as
        packages/client/public/art/tokens/<id>.webp. Then rewrites
        packages/system-dnd5e/content/token-art.json so every monster id (and its aliases)
        points at its picture.

Needs Pillow and numpy (pip install pillow numpy).
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOGUE = ROOT / 'docs/token-art/creatures.json'
PROMPTS = ROOT / 'docs/token-art/prompts.md'
OUT = ROOT / 'packages/client/public/art/tokens'
MANIFEST = ROOT / 'packages/system-dnd5e/content/token-art.json'
SRD = ROOT / 'packages/system-dnd5e/content/srd'

SIZE = 512
MARGIN = 0.03
KEYS = {'green': ('#00FF00', 'pure chroma-key green'), 'magenta': ('#FF00FF', 'pure chroma-key magenta')}
SIZES = {1: 'Medium or smaller', 2: 'Large', 3: 'Huge', 4: 'Gargantuan'}

STYLE = """Top-down fantasy battle-map token of {look}.
Camera high overhead looking almost straight down with a slight tilt (about 70 degrees), like a painted
miniature seen from above on a tabletop: we see the top of the head and shoulders and a little of the
front. The whole creature is inside the frame, centred, facing toward the bottom of the image, filling
about 90% of the width, nothing cropped. Painterly digital illustration, hand-painted texture, crisp
readable silhouette, soft rim light from the upper left, muted dark-fantasy palette with rich accent
colours. Background: one perfectly flat solid {key} ({hex}) filling the entire image, no gradient, no
floor, no cast shadow, no scenery, no particles touching the edges. No border, no circular frame, no
base, no ring, no text, no watermark. Square 1:1 image."""


def catalogue():
    return json.loads(CATALOGUE.read_text())


def monsters():
    out = {}
    for name in ('monsters-5.2.json', 'monsters-5.1.json'):
        for m in json.loads((SRD / name).read_text()):
            out[m['id']] = m
    return out


def cr_text(cr):
    return {0.125: '1/8', 0.25: '1/4', 0.5: '1/2'}.get(cr, f'{cr:g}')


def prompt_for(entry):
    hexa, key = KEYS[entry.get('background', 'green')]
    return ' '.join(STYLE.format(look=entry['look'], key=key, hex=hexa).split())


def write_prompts():
    entries, srd = catalogue(), monsters()
    lines = [
        '# Monster token prompts',
        '',
        'Generated by `python3 scripts/token-art.py prompts` from `creatures.json`; edit that, not this.',
        '',
        f'{len(entries)} pictures cover all {len(srd)} SRD monster ids (2014 and 2024 names share one).',
        'See [README.md](README.md) for naming and importing. ★ marks the ones to make first.',
        '',
    ]
    group = None
    for e in entries:
        if e['group'] != group:
            group = e['group']
            lines += [f'## {group}', '']
        m = srd[e['id']]
        names = ', '.join(f'`{a}`' for a in e.get('aliases', []))
        extra = f' · also {names}' if names else ''
        star = '★ ' if e.get('start') else ''
        lines += [
            f'### {star}{m["name"]}',
            '',
            f'File: `{e["id"]}.png` · {SIZES.get(m["size"], "Huge")} {m.get("type", "")} · CR {cr_text(m["cr"])}{extra}',
            '',
            '```text',
            prompt_for(e),
            '```',
            '',
        ]
    PROMPTS.write_text('\n'.join(lines))
    print(f'wrote {PROMPTS.relative_to(ROOT)} ({len(entries)} prompts)')


def key_out(img):
    """Alpha from the distance to the background colour, read from the image border."""
    import numpy as np

    rgb = np.asarray(img.convert('RGB')).astype(np.float32)
    border = np.concatenate([rgb[0], rgb[-1], rgb[:, 0], rgb[:, -1]])
    key = np.median(border, axis=0)
    dist = np.linalg.norm(rgb - key, axis=2)
    alpha = np.clip((dist - 70) / 90, 0, 1)
    despill(rgb, key)
    return np.dstack([rgb, alpha * 255]).astype(np.uint8)


def despill(rgb, key):
    """Takes the background's colour cast off the edges (green or magenta fringes)."""
    import numpy as np

    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    if key[1] > key[0] and key[1] > key[2]:
        np.minimum(g, np.maximum(r, b), out=g)
    elif key[0] > key[1] and key[2] > key[1]:
        excess = np.clip(np.minimum(r, b) - g, 0, None)
        r -= excess
        b -= excess


def to_token(path):
    from PIL import Image

    rgba = Image.fromarray(key_out(Image.open(path)), 'RGBA')
    box = rgba.getchannel('A').point(lambda a: 255 if a > 40 else 0).getbbox()
    if not box:
        raise ValueError('nothing left after removing the background')
    cut = rgba.crop(box)
    side = round(max(cut.size) * (1 + 2 * MARGIN))
    square = Image.new('RGBA', (side, side), (0, 0, 0, 0))
    square.paste(cut, ((side - cut.width) // 2, (side - cut.height) // 2))
    return square.resize((SIZE, SIZE), Image.LANCZOS)


def import_art(folders):
    entries = catalogue()
    canonical = {e['id']: e['id'] for e in entries}
    for e in entries:
        for a in e.get('aliases', []):
            canonical[a] = e['id']
    OUT.mkdir(parents=True, exist_ok=True)
    for folder in folders:
        for path in sorted(Path(folder).iterdir()):
            if path.suffix.lower() not in ('.png', '.jpg', '.jpeg', '.webp'):
                continue
            target = canonical.get(path.stem.lower())
            if not target:
                print(f'skipped {path.name}: not a monster id')
                continue
            to_token(path).save(OUT / f'{target}.webp', 'WEBP', quality=88, method=6)
            print(f'{path.name} -> art/tokens/{target}.webp')
    write_manifest(entries)


def write_manifest(entries):
    have = {p.stem for p in OUT.glob('*.webp')}
    art = {}
    for e in entries:
        if e['id'] in have:
            for name in [e['id'], *e.get('aliases', [])]:
                art[name] = e['id']
    MANIFEST.write_text(json.dumps(dict(sorted(art.items())), indent=2) + '\n')
    print(f'{len(have)} pictures, {len(art)} monster ids in {MANIFEST.relative_to(ROOT)}')


if __name__ == '__main__':
    if sys.argv[1:2] == ['prompts']:
        write_prompts()
    elif sys.argv[1:2] == ['import'] and len(sys.argv) > 2:
        import_art(sys.argv[2:])
    else:
        sys.exit(__doc__)
